-- Actividad de sesión y control de intentos de login.
-- Cambios aditivos: no modifican ni eliminan datos existentes.

ALTER TABLE "SESION"
  ADD COLUMN IF NOT EXISTS "ULTIMA_ACTIVIDAD" TIMESTAMP(3) NOT NULL DEFAULT CURRENT_TIMESTAMP;

CREATE INDEX IF NOT EXISTS "idx_sesion_fin_actividad"
  ON "SESION" ("FECHA_HORA_FIN", "ULTIMA_ACTIVIDAD");

CREATE TABLE IF NOT EXISTS "Intento_Login" (
  "ID_INTENTO_LOGIN" SERIAL PRIMARY KEY,
  "CLAVE" VARCHAR(64) NOT NULL,
  "FALLOS" INTEGER NOT NULL DEFAULT 0,
  "BLOQUEADO_HASTA" TIMESTAMP(3),
  "PRIMER_FALLO" TIMESTAMP(3) NOT NULL DEFAULT CURRENT_TIMESTAMP,
  "ULTIMO_FALLO" TIMESTAMP(3) NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE UNIQUE INDEX IF NOT EXISTS "uq_intento_login_clave"
  ON "Intento_Login" ("CLAVE");

CREATE INDEX IF NOT EXISTS "idx_intento_login_ultimo"
  ON "Intento_Login" ("ULTIMO_FALLO");
